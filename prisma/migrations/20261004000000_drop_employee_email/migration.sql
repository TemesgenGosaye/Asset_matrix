-- Migration: drop Employee.email and its placeholder-address machinery.
--
-- WHY: `Employee.email` existed only to satisfy a NOT NULL + unique constraint
-- that the application could not otherwise meet. Because the column could not
-- be blank, HR leaving the address out made the service synthesise a fake one
-- (`<empid-slug>@placeholder.invalid`) and report it back for later correction.
-- In practice almost nobody ever corrected it, so the employee register filled
-- up with addresses that look real, are globally unroutable, and cannot receive
-- mail. Two files had grown defensive code purely to cope: the form blanked a
-- placeholder out of its own input, and the import results advertised a list of
-- generated addresses nobody could act on.
--
-- Nothing authenticates against this column. BetterAuth signs users in on
-- `user.email`; an Employee is tied to its login account by `Employee.userid`
-- (a UUID), never by an address. An employee with no login account therefore has
-- no address to record anywhere, which is exactly the case that was being faked.
--
-- DATA-IMPACT: this REMOVES data. Every value in `Employee.email` is dropped and
-- is not recoverable from this database afterwards. That is the intent of this
-- migration — the values were placeholders or unmanaged, and keeping them
-- invites them being mistaken for real contact details.
--
-- `public."Employee"` was never created by a migration in this repository (it
-- predates it, alongside the legacy Horilla HR schema), so this file is
-- hand-written and idempotent rather than generated by `prisma migrate dev`.
--
-- SAFETY / REPLAY:
--   * The unique index is dropped before the column. Dropping the column would
--     take the index with it anyway, but dropping it explicitly keeps the
--     migration correct if a future version ever re-adds an `email` column.
--   * Both statements are guarded, so re-running against a partially applied
--     database is a no-op rather than an error.
--   * No other module reads this column. The House Requests snapshot, the
--     employee export and template, and the employee search `OR` block were all
--     updated in the same change, so nothing is left selecting a dropped column.

-- Org-scoped uniqueness on the address is meaningless once the column is gone.
DROP INDEX IF EXISTS public."Employee_org_email_key";

ALTER TABLE public."Employee"
  DROP COLUMN IF EXISTS "email";

